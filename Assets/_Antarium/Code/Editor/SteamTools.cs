using System.IO;
using System.Linq;
using System.Text;
using Antarium.Content;
using Antarium.Gameplay;
using UnityEditor;
using UnityEngine;

namespace Antarium.Editor
{
    /// <summary>
    /// Steamworks helpers: the editor opt-in for Steam, and an export of everything that has to be typed into the
    /// Steamworks site by hand (achievements with icons, stats). Files go to <c>steam/</c> in the project root.
    /// </summary>
    public static class SteamTools
    {
        public const string SteamFolder = "steam";
        const string UseSteamMenu = "Antarium/Steam/Use Steam in Editor";

        [MenuItem(UseSteamMenu)]
        static void ToggleSteamInEditor()
        {
            bool on = !EditorPrefs.GetBool(PlatformServices.SteamInEditorPref, false);
            EditorPrefs.SetBool(PlatformServices.SteamInEditorPref, on);
            Debug.Log(on
                ? "Steam in the editor is ON: play mode connects to the running Steam client, and achievements unlock on your Steam account."
                : "Steam in the editor is OFF: play mode uses the local profile only.");
        }

        [MenuItem(UseSteamMenu, true)]
        static bool ToggleSteamInEditorCheck()
        {
            Menu.SetChecked(UseSteamMenu, EditorPrefs.GetBool(PlatformServices.SteamInEditorPref, false));
            return !EditorApplication.isPlaying;
        }

        [MenuItem("Antarium/Steam/Export Achievements and Icons")]
        public static void ExportAchievements()
        {
            var db = AssetDatabase.LoadAssetAtPath<ContentDatabase>(ContentSetup.DatabasePath);
            if (db == null)
            {
                Debug.LogError("No content database: run Antarium/Setup/Create Default Content.");
                return;
            }
            var achievements = db.achievements.Where(a => a != null).OrderBy(a => a.order).ToList();
            string iconDir = Path.Combine(SteamFolder, "achievement_icons");
            Directory.CreateDirectory(iconDir);
            foreach (var old in Directory.GetFiles(iconDir, "*.png")) File.Delete(old);

            using (var icons = new AchievementIcons())
                foreach (var a in achievements)
                {
                    var (unlocked, locked) = icons.Draw(a);
                    File.WriteAllBytes(Path.Combine(iconDir, a.apiName + ".png"), unlocked.EncodeToPNG());
                    File.WriteAllBytes(Path.Combine(iconDir, a.apiName + "_locked.png"), locked.EncodeToPNG());
                    Object.DestroyImmediate(unlocked);
                    Object.DestroyImmediate(locked);
                }

            var stats = achievements.Where(a => !string.IsNullOrEmpty(a.statName)).GroupBy(a => a.statName).ToList();
            var md = new StringBuilder();
            md.AppendLine("# Steamworks: Stats & Achievements");
            md.AppendLine();
            md.AppendLine("Generated by *Antarium → Steam → Export Achievements and Icons* from `Content/Achievements`. Do not edit by hand: change the assets and export again.");
            md.AppendLine("Enter these on partner.steamgames.com → your app → **Edit Steamworks Settings → Stats & Achievements**, then **Publish** (Publish tab). See `docs/STEAM.md`.");
            md.AppendLine();
            md.AppendLine("## Stats (enter these first)");
            md.AppendLine();
            md.AppendLine("| API name | Type | Set by | Increment only | Default | Display name |");
            md.AppendLine("|---|---|---|---|---|---|");
            foreach (var s in stats)
                md.AppendLine($"| `{s.Key}` | INT | Client | yes | 0 | {StatDisplayName(s.Key)} |");
            md.AppendLine();
            md.AppendLine($"## Achievements ({achievements.Count})");
            md.AppendLine();
            md.AppendLine("Icons: `steam/achievement_icons/<API name>.png` (achieved) and `<API name>_locked.png` (unachieved), 64×64.");
            md.AppendLine("*Progress stat*: pick the stat and enter 0 as the minimum and the amount as the maximum (Steam then shows a progress bar).");
            md.AppendLine();
            md.AppendLine("| # | API name | Name | Description | Hidden | Progress stat (min – max) |");
            md.AppendLine("|---|---|---|---|---|---|");
            int n = 1;
            foreach (var a in achievements)
            {
                string progress = string.IsNullOrEmpty(a.statName) ? "" : $"`{a.statName}` (0 – {a.amount})";
                md.AppendLine($"| {n++} | `{a.apiName}` | {a.DisplayName} | {a.description.Replace("\n", " ").Replace("|", "/")} | {(a.hidden ? "yes" : "")} | {progress} |");
            }
            File.WriteAllText(Path.Combine(SteamFolder, "achievements.md"), md.ToString());
            Debug.Log($"Exported {achievements.Count} achievements, {stats.Count} stats and {achievements.Count * 2} icons to {Path.GetFullPath(SteamFolder)}.");
        }

        static string StatDisplayName(string api) => api switch
        {
            "STAT_MAX_DEPTH" => "Deepest dig (cells)",
            "STAT_MAX_ANTS" => "Most ants alive",
            "STAT_FLIGHTS" => "Nuptial Flights",
            _ => api,
        };
    }
}
